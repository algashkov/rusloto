#!/bin/bash
# Собирает офлайн-архив игры для запуска с флешки: dist/RusLoto.zip
set -e
cd "$(dirname "$0")/.."
rm -rf dist && mkdir -p dist/RusLoto
cp -R index.html css js img fonts dist/RusLoto/
python3 - <<'PY'
text = """РусЛото — игра по русскому языку (работает без интернета)

КАК ЗАПУСТИТЬ
1. Распакуйте архив (правой кнопкой -> «Извлечь всё»). Из архива напрямую не запускайте!
2. Откройте папку RusLoto и дважды щёлкните файл index.html.
3. Игра откроется в браузере. Нажмите F11 — будет во весь экран.

ЛУЧШЕ ВСЕГО открывать в Google Chrome, Яндекс.Браузере или Microsoft Edge.
Если index.html открывается не в браузере: правой кнопкой -> «Открыть с помощью» -> Chrome / Яндекс / Edge.

УПРАВЛЕНИЕ
• «Старт!» — начать игру, нажмите на бочонок — откроется вопрос.
• «Показать ответ» (или Enter), «Закрыть» (или Esc).
• 🎵 — фоновая музыка, 🔊 — звуки. Звук идёт после первого нажатия на экран.
• Нажатие на логотип над бочонками — начать игру заново.
• Открытые бочонки запоминаются, даже если закрыть браузер.

Папку можно скопировать на компьютер или оставить на флешке — важно, чтобы все
файлы и папки (css, js, img, fonts) лежали рядом с index.html.
"""
open('dist/RusLoto/KAK_ZAPUSTIT.txt', 'w', encoding='utf-8-sig', newline='\r\n').write(text)
PY
find dist -name .DS_Store -delete
(cd dist && zip -qr -X RusLoto.zip RusLoto)
du -sh dist/RusLoto.zip
